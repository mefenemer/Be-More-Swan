#!/usr/bin/env node
// scripts/build-showcase-sql.mjs — regenerate db/z-assistant-showcases.sql from db/assistant-showcases.json.
// The JSON is the editable source; the SQL is what the migration runner applies (staging first):
//   node scripts/db-migrate.mjs apply --only z-assistant-showcases --execute --yes
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../db/assistant-showcases.json', import.meta.url), 'utf8'));
const roles = Object.keys(src).filter((k) => !k.startsWith('_'));
// Dollar-quoted with a tag no content can contain, so apostrophes and quotes stay literal.
const body = (o) => `$sc$${JSON.stringify(o)}$sc$::jsonb`;

const sql = `-- db/z-assistant-showcases.sql — GENERATED by scripts/build-showcase-sql.mjs from db/assistant-showcases.json.
-- Do not edit by hand: edit the JSON and regenerate.
--
-- The long-form public page for each assistant (assistant.html): overview, how it works, features
-- with screenshots, FAQs. Its OWN table rather than a column on master_assistants, on purpose:
-- master-assistants.ts selects whole rows, so a new column there would take down the public library
-- on any database the migration had not reached yet. This table is read by assistant-showcase.ts,
-- which answers "no showcase" on 42P01 — a missing table degrades to the short page, never an outage.
-- Also points master_assistants.video at the rendered explainer (scripts/render-assistant-videos.mjs).

BEGIN;

CREATE TABLE IF NOT EXISTS assistant_showcases (
    role_key   TEXT PRIMARY KEY,
    content    JSONB NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT now()
);

INSERT INTO assistant_showcases (role_key, content) VALUES
${roles.map((r) => `    ('${r}', ${body(src[r])})`).join(',\n')}
ON CONFLICT (role_key) DO UPDATE SET content = EXCLUDED.content, updated_at = now();

${roles.map((r) => `UPDATE master_assistants SET video = '${JSON.stringify({ url: `/videos/assistants/${r}.mp4`, poster: `/videos/assistants/${r}.jpg`, title: 'Watch the overview' })}'::jsonb WHERE role_key = '${r}';`).join('\n')}

COMMIT;
`;
writeFileSync(new URL('../db/z-assistant-showcases.sql', import.meta.url), sql);
console.log(`wrote db/z-assistant-showcases.sql (${roles.length} roles)`);
