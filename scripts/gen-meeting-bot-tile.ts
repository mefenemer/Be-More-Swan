#!/usr/bin/env -S npx tsx
// The Note Taker bot's picture in a call. Each workspace's picture is drawn when its bot is sent
// (src/utils/meeting-bot-tile.ts); this script writes what that needs, and pictures to look at.
//
//   npx tsx scripts/gen-meeting-bot-tile.ts
//
// Writes:
//   src/utils/meeting-bot-tile-assets.ts   the font (Inter) and a small swan, base64, so no file has to ship with the function
//   src/utils/meeting-bot-tile-data.ts     the fallback pictures (no company name), sent if drawing fails
//   images/meeting-bot/*.jpg               examples to look at (Marmalade Productions, a long name, the fallback)
// Re-run after changing the design; commit all of them.

import fs from 'node:fs';
import path from 'node:path';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const ROOT = path.join(__dirname, '..');
const SWAN_H = 192; // drawn at 96 px on the 2560-wide tile; twice that so it stays sharp

async function main() {
    // 1. Assets.
    const font = fs.readFileSync(path.join(ROOT, 'site-fonts/inter.woff2'));
    const master = await loadImage(fs.readFileSync(path.join(ROOT, 'scripts/assets/BeMoreSwan_SwanAI-master.png')));
    const sw = Math.round((master.width / master.height) * SWAN_H);
    const sc = createCanvas(sw, SWAN_H);
    const sctx = sc.getContext('2d');
    sctx.imageSmoothingEnabled = true;
    sctx.imageSmoothingQuality = 'high';
    sctx.drawImage(master, 0, 0, sw, SWAN_H);
    const swan = await sc.encode('png');
    fs.writeFileSync(path.join(ROOT, 'src/utils/meeting-bot-tile-assets.ts'), `// GENERATED by scripts/gen-meeting-bot-tile.ts — do not edit; re-run the script instead.
// The Note Taker tile's font (Inter, SIL Open Font License 1.1) and swan, base64. Imported only by meeting-bot-tile.ts.

export const TILE_FONT_WOFF2_B64 =
    '${font.toString('base64')}';

export const TILE_SWAN_PNG_B64 =
    '${swan.toString('base64')}';
`);
    console.log(`assets: font ${(font.length / 1024).toFixed(0)} KB, swan ${(swan.length / 1024).toFixed(0)} KB`);

    // 2. Pictures (the module reads the assets just written).
    const { drawTile } = await import('../src/utils/meeting-bot-tile');
    const dir = path.join(ROOT, 'images/meeting-bot');
    fs.mkdirSync(dir, { recursive: true });
    for (const f of fs.readdirSync(dir)) if (f.endsWith('.jpg')) fs.unlinkSync(path.join(dir, f));
    const examples: [string, { assistantName: string | null; businessName: string | null }][] = [
        ['marmalade', { assistantName: 'Orbit Scribe', businessName: 'Marmalade Productions' }],
        ['long-name', { assistantName: 'Penelope the Meeting Scribe', businessName: 'The Northumberland Coastal Wedding & Events Photography Company Ltd' }],
        ['fallback', { assistantName: null, businessName: null }],
    ];
    const fallback: Record<string, string> = {};
    for (const [name, names] of examples) {
        for (const state of ['recording', 'not-recording'] as const) {
            const jpg = await drawTile(names, state);
            fs.writeFileSync(path.join(dir, `${name}-${state}.jpg`), jpg);
            if (name === 'fallback') fallback[state] = jpg.toString('base64');
            console.log(`${name}-${state}.jpg ${(jpg.length / 1024).toFixed(0)} KB`);
        }
    }
    fs.writeFileSync(path.join(ROOT, 'src/utils/meeting-bot-tile-data.ts'), `// GENERATED by scripts/gen-meeting-bot-tile.ts — do not edit; re-run the script instead.
// The Note Taker's FALLBACK picture (JPEG 1280×720, base64): sent only if drawing the workspace's own one fails.
// Pictures: images/meeting-bot/fallback-*.jpg.

export const BOT_TILE_RECORDING_JPEG_B64 =
    '${fallback.recording}';

export const BOT_TILE_NOT_RECORDING_JPEG_B64 =
    '${fallback['not-recording']}';
`);
    console.log('wrote src/utils/meeting-bot-tile-assets.ts, src/utils/meeting-bot-tile-data.ts');
}

main().catch((err) => { console.error(err); process.exit(1); });
